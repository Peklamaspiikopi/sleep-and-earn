const REVENUE_PER_VIDEO_AD = 0.00075;
const REVENUE_PER_BANNER_AD = 0.000375; // Interstitial — консервативно вдвое дешевле Rewarded

// Потолок личной доли выплаты, который показываем игроку — реальный
