// = до 144 баннеров в день (1152 монеты) — на порядок больше дневного
// потолка по роликам, что полностью ломает расчёт доли выплаты выше.
const BANNER_DAILY_LIMIT = 6;

// ==== МАГАЗИН: доп. показы на сегодня ====
//
// Чистый coin sink — трата уже заработанных монет ради удобства,
// новых монет "из воздуха" эта покупка не создаёт, безопасна для
// экономики независимо от цены. Даёт +5 к сегодняшнему остатку
// дневного лимита ролика — НЕ множитель к награде за штуку: множитель
// на маленьких числах (10-26 монет) при округлении вверх мог случайно
// пробить потолок доли выплаты, а доп. показы ратио вообще не портят
// (выплата и выручка растут вместе, см. комментарий в streakLogic.js).
const SHOP_EXTRA_PLAYS_COST = 1000;
const SHOP_EXTRA_PLAYS_AMOUNT = 5;

// ==== КОЛЕСО ФОРТУНЫ ====
//
// Не завязано на рекламную выручку вообще — это закрытая система,
// перераспределяющая уже заработанные (и уже учтённые в доле выплаты)
// монеты между игроками с отрицательным матожиданием для дома. Поэтому
// цифры просто масштабированы ×10 от первоначального расчёта — та же
// реальная ценность ставки/выигрыша в долларах, что и раньше.
//
// Матожидание (цена спина 1000):
//   40% × 0     =    0
//   30% × 500   =  150
//   15% × 1000  =  150
//   10% × 2000  =  200
//    4% × 5000  =  200
//    1% × 20000 =  200
//   -------------------
//   EV = 900 монет при цене 1000 → house edge 10% (проверено
//   Монте-Карло симуляцией на 2 млн прогонов — см. историю чата).
const WHEEL_SPIN_COST = 1000;
const WHEEL_ODDS = [
  { upTo: 40, payout: 0 },
  { upTo: 70, payout: 500 },
  { upTo: 85, payout: 1000 },
  { upTo: 95, payout: 2000 },
  { upTo: 99, payout: 5000 },
  { upTo: 100, payout: 20000 },
];

function rollWheel() {
  const roll = Math.random() * 100;
  for (const tier of WHEEL_ODDS) {
    if (roll < tier.upTo) return tier.payout;
  }
  return WHEEL_ODDS[WHEEL_ODDS.length - 1].payout;
}

// ==== МИНИ-ИГРЫ (закрытый период, валюта game_tokens) ====
//
// Один общий claim-флоу на все 3 игры (blockblast/2048/watersort):
// сыграл раунд -> обязательная реклама -> начисление. Награда —
// фикс + бонус по очкам в узком капе, чтобы даже подделанный через
// консоль счёт не давал профита сверх скромного максимума.
const GAME_DAILY_LIMIT = 8; // отдельный от video/banner дневной лимит
const GAME_MIN_WATCH_SECONDS = 15; // минимальное время сессии (примерно длина честного раунда)
const GAME_SESSION_TTL_SECONDS = 300; // на сам раунд даём 5 минут до истечения сессии
const BASE_GAME_REWARD = 8;

function computeGameBonus(score) {
  const s = Number(score) || 0;
  if (s >= 600) return 7;
  if (s >= 300) return 4;
  if (s >= 100) return 2;
  return 0;
} // итог: 8-15 game_tokens за раунд, тот же диапазон, что и у баннера/ролика по духу

