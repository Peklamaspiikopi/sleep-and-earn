// консервативно берём половину от средней выручки Rewarded-ролика
// ($0.00075/показ), то есть ≈$0.000375/показ. Целевая доля выплаты
// ~20% (баннер — бонусная фича, не хотим завышать её щедрость):
//   0.20 × $0.000375 = $0.000075 → при курсе $0.00001/монета = 7.5,
//   округлено до 8 монет (доля по факту ≈21.3% — в пределах цели).
const BANNER_REWARD = 8;
const BANNER_COOLDOWN_SECONDS = 600; // 10 минут между баннерами
const BANNER_MIN_WATCH_SECONDS = 8; // не даём засчитать показ раньше, чем реально мог закрыться сам ролик
// Отдельный суточный потолок баннеров (сбрасывается вместе с manual_limit
