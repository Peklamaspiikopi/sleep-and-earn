  SHOP_EXTRA_PLAYS_COST, SHOP_EXTRA_PLAYS_AMOUNT,
  WHEEL_SPIN_COST, WHEEL_ODDS, rollWheel,
  GAME_DAILY_LIMIT, GAME_MIN_WATCH_SECONDS, GAME_SESSION_TTL_SECONDS,
